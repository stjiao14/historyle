def map_province(pob, adm_chain=''):
    """出生地 → 现代省份：先古今地名表，再用 P131+ 行政链里的省级名称"""
    if pob:
        pob = CC.convert(pob)
        for k, v in POB_MAP.items():
            if k in pob:
                return v
    if adm_chain:
        chain = CC.convert(adm_chain)
        for k, v in CHAIN_ALIAS.items():
            if k in chain:
                return v
        for prov in PROVINCE_NAMES:
            if prov in chain:
                return prov
    return None


def fetch_country(qid):
    """单政权查询，超时重试，返回 (rows, country_label)"""
    import time

    query = QUERY_TMPL % qid
    url = ENDPOINT + '?' + urllib.parse.urlencode({'query': query, 'format': 'json'})
    for attempt, wait in enumerate([5, 15, 40], start=1):
        try:
            req = urllib.request.Request(url, headers={'Accept': 'application/sparql-results+json', 'User-Agent': UA})
            with urllib.request.urlopen(req, timeout=180) as r:
                return json.load(r)['results']['bindings']
        except Exception as e:
            print(f'  {COUNTRY_NAME[qid]} 第 {attempt} 次失败: {e}', flush=True)
            if attempt == 3:
                return []
            time.sleep(wait)


def main():
    import time

    seen = {}
    countries_of = {}
    for qid in COUNTRIES:
        bindings = fetch_country(qid)
        print(f'{COUNTRY_NAME[qid]}: {len(bindings)} 行', flush=True)
        for b in bindings:
            q = b['person']['value'].split('/')[-1]
            countries_of.setdefault(q, set()).add(COUNTRY_NAME[qid])
            if q not in seen or int(b['sitelinks']['value']) > seen[q]['_sl']:
                b['_sl'] = int(b['sitelinks']['value'])
                seen[q] = b
        time.sleep(2)  # 对端点友好一点

    rows = []
    for q, b in seen.items():
        name = CC.convert(b['personLabel']['value']).strip()
        if '(' in name or '（' in name or re.search(r'[a-zA-Z]', name):
            continue
        birth = year_of(b.get('dob', {}).get('value', ''))
        death = year_of(b.get('dod', {}).get('value', ''))
        if birth is None:
            continue
        # 用此人的全部国籍做朝代判断（避免"生于清、实为近现代人物"被归为清）
        dynasty, era = map_dynasty('|'.join(sorted(countries_of[q])), birth)
        occs = b.get('occs', {}).get('value', '')
        domains = map_domains(occs)
        province = map_province(b.get('pob', {}).get('value'), b.get('admChain', {}).get('value', ''))
        gender_raw = b.get('gender', {}).get('value', '')
        gender = '女' if '女' in gender_raw else ('男' if '男' in gender_raw else None)
        emperor = bool(re.search(r'皇帝|君主|可汗', CC.convert(occs)))
        rows.append({
            'qid': q,
            'name': name,
            'sitelinks': b['_sl'],
            'birth': birth,
            'death': death,
            'dynasty': dynasty,
            'era': era,
            'domains': domains,
            'province': province,
            'region': REGION_OF.get(province),
            'gender': gender,
            'emperor': emperor,
            'ethnicity': map_ethnicity(b.get('eths', {}).get('value', '')),
            'occs': occs,
            'pob': b.get('pob', {}).get('value'),
            'admChain': b.get('admChain', {}).get('value'),
            'eths': b.get('eths', {}).get('value'),
        })

    rows.sort(key=lambda r: -r['sitelinks'])
    with open('scripts/candidates.json', 'w', encoding='utf-8') as f:
        json.dump(rows, f, ensure_ascii=False, indent=1)

    complete = [r for r in rows if r['dynasty'] and r['domains'] and r['province'] and r['gender'] and r['death']]
    print(f'共拉取 {len(rows)} 人（去重后），字段齐全 {len(complete)} 人')
    print(f'缺省份 {sum(1 for r in rows if not r["province"])}，缺领域 {sum(1 for r in rows if not r["domains"])}，缺朝代 {sum(1 for r in rows if not r["dynasty"])}')


if __name__ == '__main__':
    main()
