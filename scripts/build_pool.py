# 朝代映射：关键词 → (dynasty, era)，按出生年细分南北宋/东西晋/东西汉
# era 为细分时期，相邻时期在猜测时算"相近"（见 src/game/compare.js）
def map_dynasty(countries, birth):
    cs = countries.split('|') if countries else []
    has = lambda *ks: any(any(k in c for k in ks) for c in cs)
    if has('中華民國', '中华民国', '中华人民共和国'):
        return '近现代', '近现代'
    if has('清'):
        return '清', '清'
    if has('明'):
        return '明', '明'
    if has('蒙古', '元'):
        return '元', '元'
    if has('辽'):
        return '辽', '宋辽金'
    if has('金'):
        return '金', '宋辽金'
    if has('西夏'):
        return '西夏', '宋辽金'
    if has('宋'):
        return ('北宋' if birth and birth < 1127 else '南宋'), '宋辽金'
    if has('唐'):
        return '唐', '唐'
    if has('隋'):
        return '隋', '隋'
    if has('北朝', '北魏', '北齐', '北周'):
        return '南北朝', '南北朝'
    if has('南朝'):
        return '南北朝', '南北朝'
    if has('晋'):
        return ('西晋' if birth and birth < 317 else '东晋'), '两晋'
    if has('曹魏', '蜀汉', '孙吴', '东吴'):
        return '三国', '三国'
    if has('漢', '汉'):
        dyn = '西汉' if birth and birth < 9 else '东汉'
        return dyn, dyn
    if has('秦'):
        return '秦', '秦'
    return None, None


