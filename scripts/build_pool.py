def map_ethnicity(eths):
    """P172 民族 → 游戏字段；无数据返回 None（由 merge 补丁/默认）"""
    if not eths:
        return None
    s = CC.convert(eths)
    for kw, eth in ETH_RULES:
        if any(k in s for k in kw):
            return eth
    if '汉' in s:
        return '汉'
    return None

