def year_of(timestr):
    """'+1911-01-01T00:00:00Z' / '1911-01-01...' → 1911；'-0551-01-01...' → -551"""
    m = re.match(r'^([+-]?)(\d+)-', timestr or '')
    if not m:
        return None
    y = int(m.group(2))
    return -y if m.group(1) == '-' else y


def map_domains(occs):
    occs = CC.convert(occs or '')
    out = []
    for kw, doms in OCC_RULES:
        if any(k in occs for k in kw):
            for d in doms:
                if d not in out:
                    out.append(d)
    return out


